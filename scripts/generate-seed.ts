// Generates supabase/seed.sql: sample blog posts and an About page, rendered
// through the same Markdown sanitiser the admin uses.
// Run: npx vite-node scripts/generate-seed.ts
import { writeFileSync } from "node:fs"
import { renderMarkdown } from "../src/lib/server/cms/markdown"

const q = (s: string | null) =>
  s === null ? "null" : `'${s.replace(/'/g, "''")}'`

const posts = [
  {
    slug: "welcome-to-base-suite",
    title: "Welcome to Base Suite",
    excerpt:
      "Your website, customers and support in one place. Here's a quick tour of what you can do from the admin portal.",
    tags: ["news", "product"],
    days: 2,
    md: `Base Suite gives your business a fast website **and** the tools to run it.

## What's inside

- **Pages & blog** — write in Markdown, preview, publish.
- **Live chat** — answer visitors from one inbox.
- **Booking** — let customers pick a time with Calendly.
- **Subscriptions** — sell plans with Stripe.

## Make it yours

Open **Admin → Brand & navigation** to set your name, logo and colours, then **Admin → Homepage** to rewrite this site's copy. Everything updates instantly — no code, no redeploys.

> Tip: delete this post from **Admin → Blog** once you've written your own.`,
  },
  {
    slug: "five-tips-for-a-homepage-that-converts",
    title: "5 tips for a homepage that converts",
    excerpt:
      "Small changes that make visitors stay, trust you and take the next step.",
    tags: ["guides", "marketing"],
    days: 9,
    md: `Your homepage has one job: help the right visitor take the next step.

1. **Say what you do in one sentence.** Put it in the hero title.
2. **Show proof early.** A stats bar or two testimonials go a long way.
3. **One primary action.** Make it obvious — "Book a demo" or "Get started".
4. **Answer objections.** An FAQ section handles the questions people won't ask.
5. **Make it fast.** Every second of load time costs you visitors.

All five are built into the homepage editor. Try reordering your features so the most important one comes first.`,
  },
  {
    slug: "how-we-handle-your-data",
    title: "How we handle your data",
    excerpt:
      "Security isn't an add-on. Here's how your information is protected.",
    tags: ["security"],
    days: 20,
    md: `We take your data seriously. A few things we do by default:

- Every database table is protected with **row-level security**.
- Staff access is **role-based** and every admin change is **audit-logged**.
- Payments are handled by **Stripe** — card details never touch our servers.
- The site loads **no third-party tracking scripts**.

Questions? [Get in touch](/contact_us).`,
  },
]

const now = Date.now()
const lines = [
  "-- Sample content for a fresh install. Generated by scripts/generate-seed.ts.",
  "-- Supabase applies this on `supabase db reset`. Safe to edit or delete.",
  "",
]
for (const p of posts) {
  const published = new Date(now - p.days * 86400_000).toISOString()
  lines.push(
    `insert into public.posts (slug, title, excerpt, body_md, body_html, author_name, tags, status, published_at) values (${q(p.slug)}, ${q(p.title)}, ${q(p.excerpt)}, ${q(p.md)}, ${q(renderMarkdown(p.md))}, 'The Base Suite team', array[${p.tags.map(q).join(", ")}]::text[], 'published', ${q(published)}) on conflict (slug) do nothing;`,
  )
}
const about = `We help small businesses look great online and stay close to their customers.

## Our story

Started by a small team who were tired of stitching together five tools to run one website.

## Get in touch

Use the chat button, [book a call](/book) or [send us a message](/contact_us).`
lines.push(
  `insert into public.cms_pages (slug, title, excerpt, body_md, body_html, status, published_at) values ('about', 'About us', 'Who we are and how we work.', ${q(about)}, ${q(renderMarkdown(about))}, 'published', now()) on conflict (slug) do nothing;`,
)
writeFileSync("supabase/seed.sql", lines.join("\n") + "\n")
console.log("wrote supabase/seed.sql")
