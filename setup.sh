#!/usr/bin/env bash
# Local dev for Base Suite: SvelteKit app (Vite) on SQLite. No database server, no Docker.
set -euo pipefail
cd "$(dirname "$0")"
PROJECT_DIR="$PWD"
PORT="${BASE_SUITE_PORT:-5173}"
PID_FILE=/tmp/base-suite-dev.pid
PORT_FILE=/tmp/base-suite-dev.port
LOG_FILE=/tmp/base-suite-dev.log
DB_FILE="$PROJECT_DIR/data/base-suite.db"

log() { printf '\033[36m%s\033[0m\n' "$*"; }
ok() { printf '\033[32m%s\033[0m\n' "$*"; }
warn() { printf '\033[33m%s\033[0m\n' "$*"; }
err() { printf '\033[31m%s\033[0m\n' "$*" >&2; }

need() { command -v "$1" >/dev/null 2>&1 || { err "$1 is required ($2)"; exit 1; }; }
check_prereqs() {
  need node "https://nodejs.org, version 22 or newer"
  need npm "comes with node"
  need lsof "macOS built in"
  need curl "macOS built in"
}

# App process: only ever kill the vite we started (PID file + command check), never a stranger on the port.
check_port() { ! lsof -iTCP:"$1" -sTCP:LISTEN -t >/dev/null 2>&1; }
owned_pid() {
  [[ -f "$PID_FILE" ]] || return 1
  local pid command
  pid="$(cat "$PID_FILE")"
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  command="$(ps -p "$pid" -o command= 2>/dev/null)" || return 1
  [[ "$command" == *"$PROJECT_DIR/node_modules/.bin/vite"* ]]
}
kill_port() {
  if owned_pid; then
    kill "$(cat "$PID_FILE")"
    for _ in {1..30}; do owned_pid || break; sleep 0.2; done
    owned_pid && { err 'App did not stop'; return 1; }
    ok 'App stopped'
  fi
  rm -f "$PID_FILE" "$PORT_FILE"
}
pick_port() {
  local p i
  for i in 0 1 2 3 4 5; do
    p=$((PORT + i))
    if check_port "$p"; then printf '%s' "$p"; return; fi
  done
  err "Ports $PORT to $((PORT + 5)) are all in use"; return 1
}
app_url() { printf 'http://localhost:%s' "$(cat "$PORT_FILE" 2>/dev/null || echo "$PORT")"; }

ensure_env() {
  [[ -f .env ]] && return
  printf '# Local development. SQLite at data/base-suite.db; see .env.example for the optional keys.\n' > .env
  ok 'Wrote .env'
}

start() {
  [[ -d node_modules ]] || { err 'Run ./setup.sh setup first'; exit 1; }
  if owned_pid; then ok "App already running at $(app_url)"; return; fi
  local port
  port="$(pick_port)"
  [[ "$port" != "$PORT" ]] && warn "Port $PORT is busy, using $port"
  mkdir -p data
  nohup "$PROJECT_DIR/node_modules/.bin/vite" dev --port "$port" --strictPort >> "$LOG_FILE" 2>&1 &
  echo $! > "$PID_FILE"
  echo "$port" > "$PORT_FILE"
  for _ in {1..40}; do
    if curl -fs -o /dev/null "http://localhost:$port/"; then ok "App ready at http://localhost:$port"; return; fi
    owned_pid || { err "App exited early; see $LOG_FILE"; tail -n 20 "$LOG_FILE"; exit 1; }
    sleep 0.5
  done
  err "App did not answer in time; see $LOG_FILE"; exit 1
}

# Cloudflare. One build serves every demo; each demo is its own Worker, D1 database and R2 bucket.
WRANGLER="${WRANGLER:-npx wrangler}"
DEMO_DIR="$PROJECT_DIR/data/demo"
DEMO_PROFILES="agency enterprise portfolio"

demo_profile() {
  local p="${1:-}"
  [[ " $DEMO_PROFILES " == *" $p "* ]] || { err "Usage: ./setup.sh ${2:-demo:local} agency|enterprise|portfolio"; exit 1; }
}
cf_build() {
  log 'Building for Cloudflare Workers'
  BUILD_TARGET=cloudflare npx vite build > /tmp/base-suite-cf-build.log 2>&1 || { err 'Build failed'; tail -n 30 /tmp/base-suite-cf-build.log; exit 1; }
  ok 'Built .svelte-kit/cloudflare'
}
# Writes wrangler.demo-<profile>.toml. The D1 ID is read from data/demo/<profile>.d1 once the database exists.
demo_config() {
  local p="$1" id="local-only"
  [[ -f "$DEMO_DIR/$p.d1" ]] && id="$(cat "$DEMO_DIR/$p.d1")"
  cat > "wrangler.demo-$p.toml" <<EOF
# Generated by ./setup.sh for the $p demo. Not committed: it holds this account's database ID.
name = "base-suite-$p"
main = "cloudflare/worker.js"
compatibility_date = "2026-10-01"
compatibility_flags = ["nodejs_compat"]

[assets]
directory = ".svelte-kit/cloudflare"
binding = "ASSETS"

[[d1_databases]]
binding = "DB"
database_name = "base-suite-$p"
database_id = "$id"

[[r2_buckets]]
binding = "MEDIA"
bucket_name = "base-suite-$p-media"

[triggers]
crons = ["*/10 * * * *"]

[observability]
enabled = true
EOF
}
# A fresh SQLite database with the sample site, exported as SQL that D1 accepts.
demo_data() {
  local p="$1" db="$DEMO_DIR/$1.db"
  need sqlite3 "brew install sqlite"
  mkdir -p "$DEMO_DIR"
  chmod 700 "$DEMO_DIR"
  rm -f "$db" "$db-wal" "$db-shm"
  [[ -f "$DEMO_DIR/$p.admin" ]] || { node -e 'console.log(require("crypto").randomBytes(15).toString("base64url"))' > "$DEMO_DIR/$p.admin"; chmod 600 "$DEMO_DIR/$p.admin"; }
  DATABASE_URL="$db" DEMO_ADMIN_PASSWORD="$(cat "$DEMO_DIR/$p.admin")" npm run --silent db:demo -- "$p"
  { echo 'PRAGMA defer_foreign_keys = true;'
    sqlite3 "$db" .dump | grep -vE '^(BEGIN TRANSACTION;|COMMIT;|PRAGMA foreign_keys)' | grep -v 'sqlite_sequence'
  } > "$DEMO_DIR/$p.sql"
  ok "Demo data: $DEMO_DIR/$p.sql (admin password in $DEMO_DIR/$p.admin)"
}
# Secrets for local runs live in .dev.vars, which wrangler reads and git ignores.
dev_vars() {
  [[ -f .dev.vars ]] && return
  local r; r() { node -e 'console.log(require("crypto").randomBytes(32).toString("hex"))'; }
  printf 'PRIVATE_SECRETS_KEY=%s\nCRON_SECRET=%s\n' "$(r)" "$(r)" > .dev.vars
  chmod 600 .dev.vars
  ok 'Wrote .dev.vars'
}
demo_pid() { printf '/tmp/base-suite-demo-%s.pid' "$1"; }
demo_port() { case "$1" in agency) echo 8787 ;; enterprise) echo 8788 ;; portfolio) echo 8789 ;; esac; }
demo_local() {
  local p="$1" state="$PROJECT_DIR/.wrangler/demo-$1" port
  port="$(demo_port "$p")"
  demo_stop "$p" >/dev/null 2>&1 || true
  check_port "$port" || { err "Port $port is in use"; exit 1; }
  demo_data "$p"
  demo_config "$p"
  dev_vars
  rm -rf "$state"
  $WRANGLER d1 execute DB --local --persist-to "$state" -c "wrangler.demo-$p.toml" --file "$DEMO_DIR/$p.sql" > /tmp/base-suite-demo-$p.log 2>&1 || { err 'Loading the data failed'; tail -n 20 /tmp/base-suite-demo-$p.log; exit 1; }
  nohup $WRANGLER dev --local --persist-to "$state" -c "wrangler.demo-$p.toml" --port "$port" >> /tmp/base-suite-demo-$p.log 2>&1 &
  echo $! > "$(demo_pid "$p")"
  for _ in {1..60}; do
    if curl -fs -o /dev/null "http://localhost:$port/"; then ok "Demo $p running in the Workers runtime at http://localhost:$port (admin@example.com)"; return; fi
    sleep 1
  done
  err "Demo did not answer; see /tmp/base-suite-demo-$p.log"; exit 1
}
demo_stop() {
  local f; f="$(demo_pid "$1")"
  [[ -f "$f" ]] || return 0
  pkill -P "$(cat "$f")" 2>/dev/null || true
  kill "$(cat "$f")" 2>/dev/null || true
  rm -f "$f"
  ok "Demo $1 stopped"
}
# Creates what is missing on Cloudflare, loads the data into an empty database, sets secrets and deploys.
demo_deploy() {
  local p="$1" out
  if [[ ! -f "$DEMO_DIR/$p.d1" ]]; then
    out="$($WRANGLER d1 create "base-suite-$p" 2>&1)" || { err "$out"; exit 1; }
    grep -oE '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}' <<<"$out" | head -n 1 > "$DEMO_DIR/$p.d1"
    [[ -s "$DEMO_DIR/$p.d1" ]] || { err "Could not read the D1 ID from: $out"; exit 1; }
    ok "Created D1 base-suite-$p"
  fi
  demo_config "$p"
  $WRANGLER r2 bucket create "base-suite-$p-media" >/dev/null 2>&1 && ok "Created R2 base-suite-$p-media" || log "R2 bucket base-suite-$p-media already there"
  if $WRANGLER d1 execute DB --remote -c "wrangler.demo-$p.toml" --command "select 1 from users limit 1" >/dev/null 2>&1; then
    log 'The database already has data; leaving it as it is'
  else
    $WRANGLER d1 execute DB --remote -y -c "wrangler.demo-$p.toml" --file "$DEMO_DIR/$p.sql"
    ok 'Loaded the demo data'
  fi
  cf_build
  $WRANGLER deploy -c "wrangler.demo-$p.toml"
  if [[ ! -f "$DEMO_DIR/$p.secrets" ]]; then
    for name in PRIVATE_SECRETS_KEY CRON_SECRET; do
      node -e 'console.log(require("crypto").randomBytes(32).toString("hex"))' | $WRANGLER secret put "$name" -c "wrangler.demo-$p.toml"
    done
    touch "$DEMO_DIR/$p.secrets"
  fi
  ok "Deployed the $p demo. Sign in as admin@example.com with the password in $DEMO_DIR/$p.admin"
}

status() {
  if owned_pid; then ok "App running at $(app_url) (pid $(cat "$PID_FILE"))"; else warn 'App stopped'; fi
  if [[ -f "$DB_FILE" ]]; then ok "Database: $DB_FILE ($(du -h "$DB_FILE" | cut -f1))"; else warn 'Database not created yet (starts with the app)'; fi
}

case "${1:-help}" in
  setup)
    check_prereqs
    npm install
    ensure_env
    npm run db:migrate
    npm run db:seed
    start ;;
  start) check_prereqs; ensure_env; start ;;
  stop) kill_port ;;
  restart) kill_port; start ;;
  status) status ;;
  logs) tail -n "${2:-100}" "$LOG_FILE" ;;
  admin) [[ -n "${2:-}" ]] || { err 'Usage: ./setup.sh admin EMAIL'; exit 1; }; npm run --silent db:admin -- "$2" ;;
  signin:reset) npm run --silent db:signin-reset ;;
  db:migrate) npm run db:migrate ;;
  db:seed) npm run --silent db:seed -- ${2:+"$2"} ;;
  db:profiles) npm run --silent db:profiles ;;
  switch) [[ -n "${2:-}" ]] || { err 'Usage: ./setup.sh switch agency|enterprise|portfolio'; exit 1; }
    npm run --silent db:seed -- "$2"; owned_pid && { kill_port; start; } || ok "Run ./setup.sh start to see it" ;;
  db:shell) need sqlite3 "brew install sqlite"; sqlite3 "$DB_FILE" ;;
  db:reset) kill_port; rm -f "$DB_FILE" "$DB_FILE-wal" "$DB_FILE-shm"; ok 'Local database removed'; npm run db:migrate; npm run --silent db:seed -- ${2:+"$2"} ;;
  cf:build) cf_build ;;
  demo:data) demo_profile "${2:-}" demo:data; demo_data "$2" ;;
  demo:local) demo_profile "${2:-}"; check_prereqs; cf_build; demo_local "$2" ;;
  demo:all) check_prereqs; cf_build; for p in $DEMO_PROFILES; do demo_local "$p"; done ;;
  demo:stop) for p in ${2:-$DEMO_PROFILES}; do demo_stop "$p"; done ;;
  demo:deploy) demo_profile "${2:-}" demo:deploy; check_prereqs; demo_data "$2"; demo_deploy "$2" ;;
  test) npm run test_run ;;
  check) ./checks.sh ;;
  build) npm run build ;;
  clean) kill_port; rm -rf node_modules .svelte-kit build; ok 'Cleaned' ;;
  help|*)
    log 'setup | start | stop | restart | status | logs [n] | admin EMAIL | switch PROFILE'
    log 'db:migrate | db:seed [PROFILE] | db:profiles | db:shell | db:reset [PROFILE] | test | check | build | clean'
    log 'switch PROFILE loads a sample site (agency, enterprise, portfolio) and restarts the app; db:profiles lists them.'
    log 'db:seed PROFILE does the same without restarting (settings refresh within 30 seconds).'
    log 'SQLite lives at data/base-suite.db. Set DATABASE_URL in .env to use Postgres instead.'
    log 'signin:reset turns sign-in and email + password back on if you are locked out.'
    log 'Locally the first account created at /login/sign_up becomes the admin; admin EMAIL grants it to another.'
    log 'Cloudflare: cf:build | demo:local PROFILE | demo:all | demo:stop [PROFILE] | demo:deploy PROFILE | demo:data PROFILE'
    log 'demo:local runs a theme demo in the Workers runtime on your machine; demo:deploy puts it on your Cloudflare account.'
    log 'Set WRANGLER to use another wrangler command, for example one that picks an account. See docs/DEPLOY_CLOUDFLARE.md.' ;;
esac
